#!/usr/bin/env python3
"""
Builds sim/demo_map.h: real OpenStreetMap roads (Overpass) and a real route
(OSRM demo server) around a point, projected to local metres. This is the same
shape of data the phone app will stream to the device.

Usage: tools/osm_demo.py [cache_dir]
"""
import json
import math
import os
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "sim", "demo_map.h")
CACHE = sys.argv[1] if len(sys.argv) > 1 else HERE

# Indiranagar, Bengaluru: 100 Feet Road towards 12th Main.
START = (12.9668, 77.6409)
END = (12.9790, 77.6445)
CENTER = ((START[0] + END[0]) / 2, (START[1] + END[1]) / 2)
RADIUS_M = 1100

# Road class → map_class_t in ui/ui_map.h
CLASSES = {
    "motorway": 3, "trunk": 3, "primary": 3, "motorway_link": 3, "trunk_link": 3, "primary_link": 3,
    "secondary": 2, "tertiary": 2, "secondary_link": 2, "tertiary_link": 2,
    "residential": 1, "unclassified": 1, "living_street": 1, "road": 1,
    "service": 0,
}


def fetch(url, data=None, name=None):
    path = os.path.join(CACHE, name)
    if os.path.exists(path):
        return json.load(open(path))
    req = urllib.request.Request(url, data=data, headers={"User-Agent": "raah-demo/0.1"})
    with urllib.request.urlopen(req, timeout=60) as r:
        body = r.read()
    open(path, "wb").write(body)
    return json.loads(body)


def project(lat, lon):
    k = 111320.0
    x = (lon - CENTER[1]) * k * math.cos(math.radians(CENTER[0]))
    y = (lat - CENTER[0]) * k
    return round(x), round(y)


def simplify(pts, tol=1.5):
    """Douglas-Peucker in metres."""
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1
    dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            dmax, idx = d, i
    if dmax <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[: idx + 1], tol)[:-1] + simplify(pts[idx:], tol)


def main():
    q = f"""[out:json][timeout:50];
way["highway"~"^({'|'.join(CLASSES)})$"](around:{RADIUS_M},{CENTER[0]},{CENTER[1]});
out geom;"""
    roads = fetch("https://overpass-api.de/api/interpreter",
                  data=urllib.parse.urlencode({"data": q}).encode(), name="overpass.json")
    route = fetch(f"https://router.project-osrm.org/route/v1/driving/{START[1]},{START[0]};{END[1]},{END[0]}"
                  "?overview=full&geometries=geojson&steps=true", name="osrm.json")

    lines, points = [], []
    for el in roads["elements"]:
        if "geometry" not in el:
            continue
        pts = simplify([project(g["lat"], g["lon"]) for g in el["geometry"]])
        cls = CLASSES[el["tags"]["highway"]]
        for i in range(0, len(pts) - 1, 254):        # split very long ways
            chunk = pts[i: i + 255]
            lines.append((cls, len(points), len(chunk)))
            points.extend(chunk)
    lines.sort(key=lambda l: l[0])                    # draw minor roads first

    r = route["routes"][0]
    rpts = simplify([project(lat, lon) for lon, lat in r["geometry"]["coordinates"]], 1.0)
    steps = [s for leg in r["legs"] for s in leg["steps"]]

    with open(OUT, "w") as f:
        f.write("/* Generated by tools/osm_demo.py from OpenStreetMap data (c) OpenStreetMap contributors, ODbL. */\n")
        f.write("#pragma once\n#include \"ui_map.h\"\n\n")
        f.write(f"static const map_pt_t demo_pts[{len(points)}] = {{\n")
        for i in range(0, len(points), 8):
            f.write("    " + " ".join(f"{{{x},{y}}}," for x, y in points[i:i + 8]) + "\n")
        f.write("};\n\n")
        f.write(f"static const map_line_t demo_lines[{len(lines)}] = {{\n")
        for cls, first, n in lines:
            f.write(f"    {{{cls}, {n}, {first}}},\n")
        f.write("};\n\n")
        f.write(f"static const map_pt_t demo_route[{len(rpts)}] = {{\n")
        for i in range(0, len(rpts), 8):
            f.write("    " + " ".join(f"{{{x},{y}}}," for x, y in rpts[i:i + 8]) + "\n")
        f.write("};\n")
        f.write("/* Steps:\n")
        for s in steps:
            m = s["maneuver"]
            x, y = project(m["location"][1], m["location"][0])
            f.write(f" *  {m['type']:<12} {m.get('modifier', ''):<12} at ({x},{y}) onto '{s.get('name', '')}'\n")
        f.write(" */\n")
    print(f"{len(lines)} roads, {len(points)} points, route {len(rpts)} points, {len(steps)} steps -> {OUT}")


if __name__ == "__main__":
    main()
